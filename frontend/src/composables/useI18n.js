const language = ref(localStorage.getItem(STORAGE_KEY) || DEFAULT_LANGUAGE)

const getNestedValue = (obj, path) => {
  return path.split('.').reduce((acc, part) => {
    if (!acc || typeof acc !== 'object') return undefined
    return acc[part]
  }, obj)
}

const interpolate = (text, params = {}) => {
  return String(text).replace(/\{(\w+)\}/g, (_, key) => {
    return params[key] !== undefined ? String(params[key]) : `{${key}}`
  })
}

export function useI18n() {
  const currentDictionary = computed(() => dictionaries[language.value] || dictionaries[DEFAULT_LANGUAGE])

  const t = (key, params = {}) => {
    const value = getNestedValue(currentDictionary.value, key)
    if (value === undefined) return key
    return interpolate(value, params)
  }

  const setLanguage = (nextLanguage) => {
    if (!dictionaries[nextLanguage]) return
    language.value = nextLanguage
    localStorage.setItem(STORAGE_KEY, nextLanguage)
  }

  const toggleLanguage = () => {
    setLanguage(language.value === 'lv' ? 'en' : 'lv')
  }

  return {
    language,
    t,
    setLanguage,
    toggleLanguage,
    languages: ['lv', 'en']
  }
}
